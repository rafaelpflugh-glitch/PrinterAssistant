"""
Printer Assistant - MX611 Print Quality Probe

Investiga comportamento de variáveis de qualidade/configuração
no ambiente PJL da impressora.

Variáveis testadas:
- RESOLUTION
- DENSITY
- ORIENTATION

Regras:
- Não altera DEFAULT.
- Não executa DEFAULT.
- Tenta SET temporário.
- Confirma INQUIRE/DINQUIRE.
- Envia um job PCL somente quando solicitado.
- Executa RESET após o teste.
- Verifica o estado final.
"""

import socket
import time


RAW_PORT = 9100
TIMEOUT = 3.0
RETRIES = 3


TESTES = [
    ("RESOLUTION", "1200"),
    ("DENSITY", "4"),
    ("ORIENTATION", "LANDSCAPE"),
]


ESC = b"\x1b"


def conectar(ip):
    ultimo_erro = None

    for tentativa in range(1, RETRIES + 1):
        try:
            print(
                f"Conectando em {ip}:{RAW_PORT} "
                f"(tentativa {tentativa}/{RETRIES})..."
            )

            sock = socket.create_connection(
                (ip, RAW_PORT),
                timeout=TIMEOUT,
            )

            sock.settimeout(TIMEOUT)

            print("Conectado.")
            return sock

        except Exception as erro:
            ultimo_erro = erro
            time.sleep(0.3)

    raise ultimo_erro


def enviar_comando(ip, comando, esperar_resposta=True):
    inicio = time.perf_counter()

    sock = conectar(ip)

    try:
        dados = (
            "\x1b%-12345X"
            f"{comando}\r\n"
            "\x1b%-12345X"
        ).encode("ascii", errors="replace")

        sock.sendall(dados)

        resposta = b""

        if esperar_resposta:
            try:
                while True:
                    bloco = sock.recv(4096)

                    if not bloco:
                        break

                    resposta += bloco

            except socket.timeout:
                pass

        tempo = time.perf_counter() - inicio

        return resposta.decode(
            "latin-1",
            errors="replace",
        ).strip(), tempo

    finally:
        sock.close()


def inquire(ip, variavel):
    resposta, tempo = enviar_comando(
        ip,
        f"@PJL INQUIRE {variavel}",
    )

    valor = extrair_valor(resposta)

    return valor, tempo


def dinquire(ip, variavel):
    resposta, tempo = enviar_comando(
        ip,
        f"@PJL DINQUIRE {variavel}",
    )

    valor = extrair_valor(resposta)

    return valor, tempo


def extrair_valor(resposta):
    if not resposta:
        return None

    linhas = [
        linha.strip()
        for linha in resposta.splitlines()
        if linha.strip()
    ]

    if not linhas:
        return None

    for linha in reversed(linhas):
        if linha.startswith("@PJL"):
            continue

        return linha

    return None


def set_variavel(ip, variavel, valor):
    comando = f"@PJL SET {variavel}={valor}"

    resposta, tempo = enviar_comando(
        ip,
        comando,
        esperar_resposta=False,
    )

    return tempo


def reset(ip):
    resposta, tempo = enviar_comando(
        ip,
        "@PJL RESET",
        esperar_resposta=False,
    )

    return tempo


def gerar_pcl_pagina(variavel, valor):
    """
    Gera uma página PCL simples.

    O objetivo é produzir uma página visualmente identificável
    para comparação entre os testes.

    Os comandos PJL de SET são colocados dentro do próprio job,
    antes do ENTER LANGUAGE=PCL.
    """

    pjl = (
        "\x1b%-12345X"
        "@PJL JOB NAME=\"PrinterAssistantQualityProbe\"\r\n"
        f"@PJL SET {variavel}={valor}\r\n"
        "@PJL ENTER LANGUAGE=PCL\r\n"
    ).encode("ascii")

    pcl = bytearray()

    # Reset PCL
    pcl += ESC + b"E"

    # Orientação da página.
    #
    # O valor PJL continua sendo enviado acima.
    # Este comando PCL só é usado quando o teste é ORIENTATION,
    # permitindo comparar comportamento explicitamente.
    if variavel == "ORIENTATION":
        if valor.upper() == "LANDSCAPE":
            pcl += ESC + b"&l1O"
        else:
            pcl += ESC + b"&l0O"

    # Texto simples.
    #
    # Fonte Courier 12
    pcl += ESC + b"(s0p12h0s0b4099T"

    texto = (
        "\r\n"
        "\r\n"
        "PRINTER ASSISTANT\r\n"
        "MX611 PRINT QUALITY PROBE\r\n"
        "\r\n"
        f"VARIABLE: {variavel}\r\n"
        f"TEST VALUE: {valor}\r\n"
        "\r\n"
        "This page was generated by Printer Assistant.\r\n"
        "\r\n"
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ\r\n"
        "abcdefghijklmnopqrstuvwxyz\r\n"
        "0123456789\r\n"
        "\r\n"
        "1234567890 1234567890 1234567890\r\n"
        "\r\n"
    )

    texto_bytes = texto.encode(
        "ascii",
        errors="replace",
    )

    pcl += texto_bytes

    # Form feed
    pcl += b"\x0c"

    # Finaliza linguagem PCL
    pcl += ESC + b"%-12345X"

    # End job
    pcl += b"@PJL EOJ NAME=\"PrinterAssistantQualityProbe\"\r\n"
    pcl += ESC + b"%-12345X"

    return pjl + bytes(pcl)


def enviar_job(ip, variavel, valor):
    dados = gerar_pcl_pagina(
        variavel,
        valor,
    )

    inicio = time.perf_counter()

    sock = conectar(ip)

    try:
        sock.sendall(dados)
    finally:
        sock.close()

    tempo = time.perf_counter() - inicio

    return len(dados), tempo


def estado_variavel(ip, variavel):
    corrente, tempo_inq = inquire(
        ip,
        variavel,
    )

    padrao, tempo_dinq = dinquire(
        ip,
        variavel,
    )

    return (
        corrente,
        padrao,
        tempo_inq,
        tempo_dinq,
    )


def imprimir_estado(
    ip,
    variavel,
    titulo,
):
    print()
    print(titulo)
    print("-" * 72)

    corrente, padrao, tempo_inq, tempo_dinq = estado_variavel(
        ip,
        variavel,
    )

    print(f"INQUIRE  : {corrente}")
    print(f"DINQUIRE : {padrao}")
    print(f"Tempo INQ: {tempo_inq:.3f}s")
    print(f"Tempo DIN: {tempo_dinq:.3f}s")

    return corrente, padrao


def testar_variavel(ip, variavel, valor):
    print()
    print("=" * 72)
    print(f"TESTE: {variavel}={valor}")
    print("=" * 72)

    corrente_original, default_original = imprimir_estado(
        ip,
        variavel,
        "Estado original:",
    )

    print()
    print(
        f"Enviando @PJL SET {variavel}={valor}"
    )

    tempo_set = set_variavel(
        ip,
        variavel,
        valor,
    )

    print(
        f"SET enviado em {tempo_set:.3f}s"
    )

    corrente_set, default_set = imprimir_estado(
        ip,
        variavel,
        "Estado após SET:",
    )

    set_confirmado = (
        corrente_set is not None
        and corrente_set.upper() == str(valor).upper()
    )

    default_preservado = (
        default_set == default_original
    )

    if set_confirmado:
        print(
            f"✓ SET {variavel}={valor} "
            "foi confirmado no ambiente corrente."
        )
    else:
        print(
            f"✗ SET {variavel}={valor} "
            "não foi confirmado."
        )

    if default_preservado:
        print(
            "✓ DEFAULT permaneceu inalterado."
        )
    else:
        print(
            "✗ DEFAULT foi alterado inesperadamente."
        )

    print()
    print(
        "O próximo job será enviado com:"
    )
    print(
        f"@PJL SET {variavel}={valor}"
    )
    print()
    print(
        "A página será uma página PCL simples."
    )
    print(
        "Observe fisicamente o comportamento."
    )

    input(
        "Pressione ENTER para enviar o job..."
    )

    try:
        quantidade, tempo_job = enviar_job(
            ip,
            variavel,
            valor,
        )

        print()
        print("Job enviado.")
        print(
            f"Bytes enviados: {quantidade}"
        )
        print(
            f"Tempo:          {tempo_job:.3f}s"
        )

    except Exception as erro:
        print()
        print("✗ ERRO AO ENVIAR JOB")
        print(
            f"{type(erro).__name__}: {erro}"
        )

    print()
    print("Enviando @PJL RESET...")

    tempo_reset = reset(ip)

    print(
        f"RESET enviado em {tempo_reset:.3f}s"
    )

    corrente_final, default_final = imprimir_estado(
        ip,
        variavel,
        "Estado após RESET:",
    )

    reset_confirmado = (
        corrente_final == corrente_original
        and default_final == default_original
    )

    if reset_confirmado:
        print()
        print(
            "✓ RESET restaurou o estado original."
        )
    else:
        print()
        print(
            "✗ RESET NÃO restaurou exatamente "
            "o estado original."
        )

    print()
    print("Resumo do teste:")
    print(
        f"Original corrente : {corrente_original}"
    )
    print(
        f"Original default  : {default_original}"
    )
    print(
        f"Após SET corrente : {corrente_set}"
    )
    print(
        f"Após SET default  : {default_set}"
    )
    print(
        f"Final corrente    : {corrente_final}"
    )
    print(
        f"Final default     : {default_final}"
    )

    return {
        "variavel": variavel,
        "valor": valor,
        "set_confirmado": set_confirmado,
        "default_preservado": default_preservado,
        "reset_confirmado": reset_confirmado,
        "original_corrente": corrente_original,
        "original_default": default_original,
        "final_corrente": corrente_final,
        "final_default": default_final,
    }


def main():
    print("=" * 72)
    print("PRINTER ASSISTANT - MX611 PRINT QUALITY PROBE")
    print("=" * 72)

    ip = input(
        "Digite o IP da impressora: "
    ).strip()

    if not ip:
        print("IP inválido.")
        return

    print()
    print(f"Impressora: {ip}")
    print(f"RAW:        {RAW_PORT}")
    print()

    print("Este teste:")
    print()
    print("- NÃO altera DEFAULT.")
    print("- testa SET temporário.")
    print("- envia um job PCL por variável.")
    print("- executa RESET após cada teste.")
    print("- confirma a restauração.")
    print()
    print("Variáveis:")
    print()
    print("- RESOLUTION=1200")
    print("- DENSITY=4")
    print("- ORIENTATION=LANDSCAPE")
    print()

    resposta = input(
        "A impressora irá imprimir três páginas. "
        "Continuar? [S/N]: "
    ).strip().upper()

    if resposta not in ("S", "SIM"):
        print("Teste cancelado.")
        return

    resultados = []

    for variavel, valor in TESTES:
        try:
            resultado = testar_variavel(
                ip,
                variavel,
                valor,
            )

            resultados.append(resultado)

        except Exception as erro:
            print()
            print("=" * 72)
            print(
                f"✗ ERRO NO TESTE {variavel}"
            )
            print("=" * 72)
            print(
                f"{type(erro).__name__}: {erro}"
            )

            print()
            print(
                "Tentando RESET de segurança..."
            )

            try:
                reset(ip)
                print(
                    "✓ RESET enviado."
                )
            except Exception as reset_erro:
                print(
                    "✗ Não foi possível enviar RESET:"
                )
                print(
                    f"{type(reset_erro).__name__}: "
                    f"{reset_erro}"
                )

    print()
    print("=" * 72)
    print("RESULTADO FINAL")
    print("=" * 72)

    print()

    for resultado in resultados:
        variavel = resultado["variavel"]

        print(
            f"{variavel:<12} "
            f"SET={'✓' if resultado['set_confirmado'] else '✗'} "
            f"RESET={'✓' if resultado['reset_confirmado'] else '✗'} "
            f"DEFAULT={'✓' if resultado['default_preservado'] else '✗'}"
        )

    print()
    print(
        "Nenhum comando DEFAULT foi executado."
    )
    print(
        "Nenhuma configuração permanente deveria "
        "ter sido alterada."
    )
    print()
    print(
        "Analise fisicamente as páginas impressas."
    )


if __name__ == "__main__":
    main()